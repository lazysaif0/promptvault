# crescent moon: circle A minus circle B
moon = set()
for y in range(9):
    for x in range(9):
        a = math.hypot(x - 4, y - 4) <= 4.3
        b = math.hypot(x - 6.3, y - 2.7) <= 3.6
        if a and not b:
            moon.add((x, y))

# magnifier: ring + handle
search = set()
for y in range(9):
    for x in range(9):
        d = math.hypot(x - 3.5, y - 3.5)
        if 1.9 <= d <= 3.5:
            search.add((x, y))
search |= {(6, 6), (7, 7), (8, 8), (6, 7), (7, 6)}

