"""
make_sprites.py - generate app/templates/partials/sprites.html (the pixel-art icons).

Every icon is drawn as an ASCII map below (X = a filled pixel). Edit a map, run
    python tools/make_sprites.py
and the SVG sprite sheet is rewritten. Needs no extra packages.
"""
import os
import math

OUT = os.path.join(os.path.dirname(os.path.dirname(os.path.abspath(__file__))), "app", "templates", "partials", "sprites.html")


def parse(rows):
    return {(x, y) for y, r in enumerate(rows) for x, ch in enumerate(r) if ch == "X"}


def path(px, dx=0, dy=0):
    """Merge horizontal runs of pixels into compact SVG path commands."""
    out = []
    for y in sorted({p[1] for p in px}):
        xs = sorted(p[0] for p in px if p[1] == y)
        start = prev = xs[0]
        for x in xs[1:] + [None]:
            if x is None or x != prev + 1:
                w = prev - start + 1
                out.append(f"M{start + dx} {y + dy}h{w}v1h-{w}z")
                if x is not None:
                    start = x
            prev = x if x is not None else prev
    return "".join(out)


def ring(px):
    """Outline: every empty pixel touching the shape (4-neighbour dilation)."""
    r = set()
    for x, y in px:
        for dx, dy in ((1, 0), (-1, 0), (0, 1), (0, -1)):
            q = (x + dx, y + dy)
            if q not in px:
                r.add(q)
    return r


def pair(name, rows, pad=1):
    """<name>-fill (the shape) and <name>-line (1px outline) sharing one viewBox."""
    px = parse(rows)
    w = max(p[0] for p in px) + 1 + 2 * pad
    h = max(p[1] for p in px) + 1 + 2 * pad
    shifted = {(x + pad, y + pad) for x, y in px}
    o = ring(shifted)
    vb = f"0 0 {w} {h}"
    return (f'<symbol id="{name}-fill" viewBox="{vb}"><path d="{path(shifted)}"/></symbol>\n'
            f'<symbol id="{name}-line" viewBox="{vb}"><path d="{path(o)}"/></symbol>\n')


def single(name, px, w, h):
    return f'<symbol id="{name}" viewBox="0 0 {w} {h}"><path d="{path(px)}"/></symbol>\n'


